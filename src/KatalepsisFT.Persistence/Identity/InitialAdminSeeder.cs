using KatalepsisFT.Domain.Access;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;

namespace KatalepsisFT.Persistence.Identity;

public enum InitialAdminOutcome
{
    Created,
    UsersAlreadyExist,
    NotConfigured,
}

/// <summary>Creates the roles, and the first Admin when the system has no user at all. Safe to run on every deploy.</summary>
public sealed class InitialAdminSeeder(UserManager<AppUser> users, RoleManager<IdentityRole<int>> roles)
{
    public async Task EnsureRolesAsync()
    {
        foreach (string role in Roles.All)
        {
            if (!await roles.RoleExistsAsync(role))
            {
                Throw(await roles.CreateAsync(new IdentityRole<int>(role)));
            }
        }
    }

    public async Task<InitialAdminOutcome> EnsureInitialAdminAsync(string? email, string? password, CancellationToken cancellationToken)
    {
        if (await users.Users.AnyAsync(cancellationToken))
        {
            return InitialAdminOutcome.UsersAlreadyExist;
        }

        if (string.IsNullOrWhiteSpace(email) || string.IsNullOrWhiteSpace(password))
        {
            return InitialAdminOutcome.NotConfigured;
        }

        AppUser admin = new()
        {
            UserName = email.Trim(),
            Email = email.Trim(),
            EmailConfirmed = true,
            DisplayName = "Administrator",
            MustChangePassword = true,
            CreatedAt = DateTimeOffset.UtcNow,
            LockoutEnabled = true,
        };

        // The initial password is generated by the platform and may not meet the password rules; it must be changed
        // at first sign-in anyway, so it is stored without running the rules.
        admin.PasswordHash = users.PasswordHasher.HashPassword(admin, password);
        Throw(await users.CreateAsync(admin));
        Throw(await users.AddToRoleAsync(admin, Roles.Admin));
        return InitialAdminOutcome.Created;
    }

    private static void Throw(IdentityResult result)
    {
        if (!result.Succeeded)
        {
            throw new InvalidOperationException(string.Join("; ", result.Errors.Select(e => e.Description)));
        }
    }
}
